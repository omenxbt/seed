use anchor_lang::prelude::*;

#[error_code]
pub enum SeedError {
    #[msg("The raise is not live.")] NotLive,
    #[msg("The raise has not filled.")] NotFilled,
    #[msg("The raise has not seeded.")] NotSeeded,
    #[msg("The raise has not refunded.")] NotRefunded,
    #[msg("The deadline has passed.")] DeadlinePassed,
    #[msg("The deadline has not passed.")] DeadlineNotPassed,
    #[msg("The deadline must be between the minimum and the maximum.")] BadDeadline,
    #[msg("The target is zero.")] ZeroTarget,
    #[msg("The target is over the cap at today's SOL price.")] OverCap,
    #[msg("The target is under the minimum raise (81 SOL on mainnet; a USDC raise meets its worth at today's SOL price).")] TargetBelowMinimum,
    #[msg("The SOL price is stale: the Pyth feed has not updated recently.")] StalePrice,
    #[msg("The pair asset must be SOL or USDC.")] BadPair,
    #[msg("The team share must be under 100%.")] BadTeamShare,
    #[msg("The unlocks must add up to exactly 100%.")] ScheduleSum,
    #[msg("The unlocks are out of order.")] ScheduleOrder,
    #[msg("The schedule is empty or has too many dates, a slice with no share, two shapes at once, or a team share of zero with a schedule.")] BadSchedule,
    #[msg("The name or ticker is too long or empty.")] BadName,
    #[msg("The metadata URI must be an https:// or ar:// address of at most 200 characters (Arweave on mainnet).")] BadUri,
    #[msg("The amount is zero.")] ZeroAmount,
    #[msg("The raise is full.")] Full,
    #[msg("Buying is off: this raise was flagged for fraud.")] Flagged,
    #[msg("This X account cannot open a raise.")] Blacklisted,
    #[msg("The attestation is missing, malformed or not from the attestor.")] BadAttestation,
    #[msg("The attestation has expired.")] AttestationExpired,
    #[msg("Only the founder can do that.")] NotFounder,
    #[msg("Only the admin can do that.")] NotAdmin,
    #[msg("That is not the Pyth SOL/USD price account, or it is not fully verified.")] BadPriceAccount,
    #[msg("Those terms are out of range.")] BadConfig,
    #[msg("This wallet already has a live raise. One at a time.")] OneLiveRaise,
    #[msg("The raise named as this wallet's live one was not passed in.")] PrevRaiseMissing,
    #[msg("This raise already has an X account linked.")] XAlreadyLinked,
    #[msg("A refunded raise cannot link an X account.")] RaiseOver,
    #[msg("The X handle's blacklist account was not passed in.")] XBlacklistMissing,
    #[msg("Only the pending admin can accept the handover.")] NotPendingAdmin,
    #[msg("Test mode exists only in devnet builds, and only with the devnet proof account.")] TestModeNotAllowed,
    #[msg("That seeding step is not next.")] WrongStep,
    #[msg("The seeding timeout has not passed.")] TimeoutNotPassed,
    #[msg("Already claimed.")] AlreadyClaimed,
    #[msg("Nothing to claim.")] NothingToClaim,
    #[msg("The payout wallet change is not due yet.")] ChangeNotDue,
    #[msg("No payout wallet change is pending.")] NoChangePending,
    #[msg("The account does not match the raise.")] WrongAccount,
    #[msg("Arithmetic overflow.")] Overflow,
}
